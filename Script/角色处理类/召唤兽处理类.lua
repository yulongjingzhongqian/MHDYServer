			end

			if 单机设置 then
				if self.数据[i].宠物图鉴系统 ~= nil then
					self.数据[i].宠物图鉴系统 = nil
				end

				if self.数据[i].模型 == "魔化童子" then
					self.数据[i].模型 = "魔化毗舍童子"
				elseif self.数据[i].模型 == "小仙灵" then
					self.数据[i].模型 = "小神灵"
				elseif self.数据[i].模型 == "进阶小仙灵" then
					self.数据[i].模型 = "进阶小神灵"
