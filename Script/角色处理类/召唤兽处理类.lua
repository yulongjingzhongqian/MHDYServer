	self.数据[编号].耐力 = self.数据[编号].等级 + 初始潜力
	self.数据[编号].敏捷 = self.数据[编号].等级 + 初始潜力
	self.数据[编号].潜力 = self.数据[编号].等级 * (服务端参数.宝宝升级潜能点 + 神兽转生潜能点加成) + self.数据[编号].灵性 * 2

