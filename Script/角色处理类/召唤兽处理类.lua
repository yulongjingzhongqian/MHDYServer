		local ss = 1

		if self.数据[编号].种类 == "神兽" then
			ss = 2
		end

		转生加成 = 转生五维 * tonumber(self.数据[编号].转生) * ss
	end

	if self.数据[编号].种类 == "神兽" then
		初始潜力 = 神兽初始潜力

		if self.数据[编号].转生 ~= nil and self.数据[编号].转生 >= 2 then
			神兽转生潜能点加成 = 神兽转生潜能点加成 + qz(服务端参数.宝宝升级潜能点 / 5)
		end



		if self.数据[编号].天生神兽 == true then
			初始潜力 = 天生神兽初始潜力
			神兽转生潜能点加成 = 神兽转生潜能点加成 + qz(服务端参数.宝宝升级潜能点 / 5)
		end

