				self.数据[i].统御属性 = {
					体质 = 0,
					力量 = 0,
					敏捷 = 0,
					耐力 = 0,
					魔力 = 0
				}
			end

			if self.数据[i].种类 == "神兽" then
				for k, v in pairs(神兽资质上限) do
					if v < self.数据[i][k] then
						self.数据[i][k] = v

