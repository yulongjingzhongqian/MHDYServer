					self.数据[i].参战信息 = nil
					玩家数据[数字id].角色.数据.参战信息 = nil
				else
					玩家数据[数字id].角色.数据.参战宝宝 = {}
					玩家数据[数字id].角色.数据.参战宝宝 = self.数据[i]
					玩家数据[数字id].角色.数据.参战信息 = 1
					self.数据[i].参战信息 = 1
				end
			end

			self:刷新套装效果(i)
			取召唤兽排行榜评分(self.数据[i], 玩家数据[数字id].角色.数据.名称)
		end
	end
