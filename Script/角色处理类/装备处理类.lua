				道具.灵力 = math.floor((熟练度影响计算(等级 * 0.2 + 6, 等级 * 0.4 + 6, 熟练度) + 熟练度影响计算(灵气 * 0.1, 灵气 * 0.2, 熟练度)) * 额外加成)
