					道具[类型] = math.floor((熟练度影响计算(等级 * 0.3 + 10, 等级 * 0.6 + 10, 熟练度) + 熟练度影响计算(灵气 * 0.15, 灵气 * 0.3, 熟练度)) * 额外加成)
