				elseif 类型 == "敏捷" or 类型 == "体质" or 类型 == "力量" or 类型 == "耐力" or 类型 == "魔力" then
					道具[类型] = math.floor((熟练度影响计算(等级 / 10 + 2, 等级 / 10 + 10, 熟练度) + 熟练度影响计算(灵气 / 20, 灵气 / 10, 熟练度)) * 额外加成)
