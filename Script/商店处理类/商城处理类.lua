				"#Y/两银子购买了#R/" ..
				math.abs(内容.数量 * (self.商品组[self.购买组号][self.购买分类][self.购买编号].数量 or 1)) ..
				"个" .. self.商品组[self.购买组号][self.购买分类][self.购买编号].名称)
		end
	elseif self.购买分类 == "比武积分" or self.购买分类 == "副本积分" or self.购买分类 == "种族积分" or self.购买分类 == "妖魔积分" or self.购买分类 == "军功" then
