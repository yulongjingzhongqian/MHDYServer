		玩家数据[id].角色:添加银子(200000000, "商城购买", 1)
		常规提示(id, "#Y/恭喜你从商城购买了#R/两亿两银子#Y/。")
	elseif self.商品组[self.购买组号][self.购买分类][self.购买编号].名称 == "60级随机灵饰指南书" then
		玩家数据[id].道具:给予道具(id, "灵饰指南书", {
