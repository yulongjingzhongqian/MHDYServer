			return
		end

		if self.购买数量 > 1 and self.商品组[self.购买组号][self.购买分类][self.购买编号].可叠加 ~= nil then
			发送数据(玩家数据[id].连接id, 7, "#y/贵重物品每次买一个")

			self.允许购买 = false

			return
		else
			self.允许购买 = true
		end

		if self.允许购买 then
			if self.购买分类 == "比武积分" then
				if 玩家数据[id].角色:扣除积分(购买总价, "积分商城", 1) == false then
