					常规提示(id, "你的副本积分不足。")

					return
				end
			elseif self.购买分类 == "妖魔积分" then
				if 玩家数据[id].角色:扣除妖魔积分(购买总价, "积分商城", 1) == false then
					常规提示(id, "你的妖魔积分不足。")

					return
				end
			elseif self.购买分类 == "种族积分" then
				if 玩家数据[id].角色:扣除种族积分(购买总价, "积分商城", 1) == false then
