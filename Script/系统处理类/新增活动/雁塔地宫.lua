function 雁塔地宫:对话处理(id, 名称, 事件, 地图编号)
	if 事件 == "送我进去（队伍最低层数）" then
		if not 调试模式 and (玩家数据[id].队伍 == 0 or 取队伍人数(id) < 3 or 取队伍最低等级(玩家数据[id].队伍, 50)) then
			添加最后对话(id, "地宫对于少侠来说还是过于危险了，还是好好磨练一番再来吧。（进入地宫需要等级≥50，人数≥3人）")

			return
		end

		for n = 1, #队伍数据[玩家数据[id].队伍].成员数据 do
			local cyid = 队伍数据[玩家数据[id].队伍].成员数据[n]

			if 玩家数据[cyid].角色.数据.飞行中 then
				添加最后对话(id, "#Y/地宫中凶险万分，少侠还是走路比较安全。（禁止飞行）")

				return
			end
		end

		local 层数, aidi = self:取地宫最低层数(id)

		添加最后对话(id, "目前你们队伍中层数最低的玩家是#Y" .. 玩家数据[aidi].角色.数据.名称 .. "，层数：" .. 层数 .. "层#W。我的能力只能送你们去这个层数，是否考虑好了？", {
			"请送我们过去吧",
			"我再想想"
		})
	elseif 事件 == "请送我们过去吧" then
		if not 调试模式 and (玩家数据[id].队伍 == 0 or 取队伍人数(id) < 3 or 取队伍最低等级(玩家数据[id].队伍, 50)) then
			添加最后对话(id, "地宫对于少侠来说还是过于危险了，还是好好磨练一番再来吧。（进入地宫需要等级≥50，人数≥3人）")

			return
		end

		local 层数, aidi = self:取地宫最低层数(id)

		地图处理类:跳转地图(id, self.ditu.层数[层数], self.ditu.传送坐标[层数].x, self.ditu.传送坐标[层数].y)
	elseif 事件 == "了解地宫规则" then
		添加最后对话(id, "雁塔地宫为不限时挑战模式，每日可进行30次挑战，每天晚12点会自动下降10层挑战层数，每周日晚12点将自动归零。每次挑战按队伍中最低层数来进行。")
	elseif 事件 == "我来会会你" then
		if 玩家数据[id].队伍 == 0 or 取队伍人数(id) < 3 or 取队伍最低等级(玩家数据[id].队伍, 50) then
			添加最后对话(id, "地宫对于少侠来说还是过于危险了，还是好好磨练一番再来吧。（需要等级≥50，人数≥3人）")

			return
		end

		local 怪物层数 = 地图编号 - 3000 + 1
		local 层数, aidi = self:取地宫最低层数(id)

		if 层数 >= 70 then
			return 添加最后对话(id, "目前地宫只更新至70层。")
		end

		for n = 1, #队伍数据[玩家数据[id].队伍].成员数据 do
			if 队伍处理类:取是否助战(玩家数据[id].队伍, n) == 0 then
				local cyid = 队伍数据[玩家数据[id].队伍].成员数据[n]

				if 怪物层数 ~= 层数 then
					添加最后对话(id, "你们目前应该挑战的层数为：" .. 层数 .. "层")

					return
				end

