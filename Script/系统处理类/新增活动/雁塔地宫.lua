local 雁塔地宫 = class()

function 雁塔地宫:初始化()
	self.活动开关 = false
	self.间隔 = 30
	self.数据 = {}

	if f函数.文件是否存在("tysj/雁塔地宫.txt") == false then
		写出文件("tysj/雁塔地宫.txt", table.tostring({}))
	else
		self.数据 = table.loadstring(读入文件("tysj/雁塔地宫.txt"))
	end

	self:加载数据()
	self:更新怪物()
end

function 雁塔地宫:每日下调()
	for k, v in pairs(self.数据) do
		v.层数 = v.层数 - 10
		v.次数 = 0

		if v.层数 < 1 then
			v.层数 = 1
		elseif v.层数 > 40 then
			v.层数 = 40
		end
	end

	广播消息({
		频道 = "hd",
		内容 = format("#R(雁塔地宫)#Y新的一天开始了，各位少侠的地宫层数减少了#G10#Y层！")
	})
	写出文件("tysj/雁塔地宫.txt", table.tostring(self.数据))
end

function 雁塔地宫:每周归零()
	self.数据 = {}

	广播消息({
		频道 = "hd",
		内容 = format("#R(雁塔地宫)#Y新的一周开始了，雁塔地宫层数已经全部重置！")
	})
	写出文件("tysj/雁塔地宫.txt", table.tostring({}))
end

function 雁塔地宫:取地宫最低层数(id)
	local tab = {}
	local 队伍id = 玩家数据[id].队伍

	for n = 1, #队伍数据[队伍id].成员数据 do
		if 队伍处理类:取是否助战(队伍id, n) == 0 then
			if not self.数据[队伍数据[队伍id].成员数据[n]] then
				self.数据[队伍数据[队伍id].成员数据[n]] = {
					次数 = 0,
					层数 = 1
				}
			end

			tab[n] = {
				cs = self.数据[队伍数据[队伍id].成员数据[n]].层数 or 1,
				id = 队伍数据[队伍id].成员数据[n]
			}
		end
	end

	table.sort(tab, function (a, b)
		return a.cs < b.cs
	end)

	return tab[1].cs, tab[1].id
end

